#!/usr/bin/env python3
"""Write firmware/include/engine_lab_data.h for the `engine_lab` test firmware.

Single source of truth is tools/engine_lab.py: the grains, presets, speaker EQ and noise filter are taken from
there, so the firmware plays what the previews were rendered from (firmware/include/engine_synth2.h mirrors
engine_lab.Synth2).

Usage: python tools/make_engine_lab_header.py [output.h]
"""
import math, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import engine_lab as L  # noqa: E402

ORDER = ["diesel", "petrol4", "v8", "v12"]
MAXPAT = 8


def f(v):
    s = "%.9g" % v
    if "." not in s and "e" not in s:
        s += ".0"   # "28f" is not a valid C++ literal, "28.0f" is
    return s + "f"


def arr(vals):
    return "{" + ", ".join(f(v) for v in vals) + "}"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(L.ROOT, "firmware", "include", "engine_lab_data.h")
    synths = [L.Synth2(L.PRESETS[n]) for n in ORDER]
    glen = max(L.PRESETS[n]["length"] for n in ORDER)
    lines = ["// Generated by tools/make_engine_lab_header.py from tools/engine_lab.py - do not edit.",
             "// Synthesised combustion grains (original, no third-party audio), presets and the speaker EQ.",
             "#pragma once", "#include <stdint.h>", "",
             "#define LAB_PRESETS %d" % len(ORDER), "#define LAB_VARIANTS 4", "#define LAB_GRAIN_MAX %d" % glen,
             "#define LAB_PATTERN_MAX %d" % MAXPAT, ""]
    lines.append("static const char* const LAB_PRESET_NAMES[LAB_PRESETS] = {%s};" % ", ".join('"%s"' % n for n in ORDER))
    for setname, attr in (("LAB_GRAIN_BASE", "base"), ("LAB_GRAIN_BRIGHT", "bright")):
        lines.append("static const int16_t %s[LAB_PRESETS][LAB_VARIANTS][LAB_GRAIN_MAX] = {" % setname)
        for s in synths:
            lines.append("{")
            for g in getattr(s, attr):
                vals = [int(round(max(-1.0, min(1.0, v)) * 32767)) for v in g] + [0] * (glen - len(g))
                lines.append("{" + ",".join(str(v) for v in vals) + "},")
            lines.append("},")
        lines.append("};")
    lines += ["", "struct LabPreset {", "  float fireIdle, fireMax;", "  int grainLen, patternLen;",
              "  float ampPattern[LAB_PATTERN_MAX], timePattern[LAB_PATTERN_MAX];",
              "  float noiseLo, noiseHi, envK, outGain;", "  float noiseBp[5];  // b0 b1 b2 a1 a2", "};",
              "static const LabPreset LAB_PRESET[LAB_PRESETS] = {"]
    for n, s in zip(ORDER, synths):
        p = L.PRESETS[n]
        k = len(p["amp_pattern"])
        pad = lambda v: list(v) + [0.0] * (MAXPAT - len(v))
        lines.append("  {%s, %s, %d, %d, %s, %s, %s, %s, %s, %s, %s},  // %s" % (
            f(p["fire"][0]), f(p["fire"][1]), p["length"], k, arr(pad(p["amp_pattern"])), arr(pad(p["time_pattern"])),
            f(p["noise_level"][0]), f(p["noise_level"][1]), f(s.env_k), f(p["out_gain"]),
            arr(L.biquad("bp", *p["noise_bp"])), n))
    lines.append("};")
    lines += ["", "// Speaker EQ (tools/engine_lab.py SPEAKER_EQ): biquads b0 b1 b2 a1 a2, applied in this order",
              "#define LAB_EQ_STAGES %d" % len(L.SPEAKER_EQ),
              "static const float LAB_EQ[LAB_EQ_STAGES][5] = {" + ", ".join(arr(c) for c in L.SPEAKER_EQ) + "};", ""]
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote %s: %d presets, grains up to %d samples" % (out, len(ORDER), glen))


if __name__ == "__main__":
    main()
