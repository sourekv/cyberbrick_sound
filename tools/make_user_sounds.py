#!/usr/bin/env python3
"""Convert a user-supplied engine start recording into firmware/include/user_sounds.h.

The recording's origin/license is unknown (see assets/samples/LICENSE-SAMPLES.md), so the
generated header is listed in .gitignore and must NOT be committed. Run this locally:

    python tools/make_user_sounds.py "C:/path/to/teplý start.wav"

What it does:
  * reads an 8-bit or 16-bit mono WAV (22.05 kHz expected, the firmware rate)
  * trims the leading silence
  * finds a seamless loop inside the steady idle part (LOOP_START .. LOOP_END) by comparing
    the audio just before the loop end with the audio just before the loop start
  * writes START_WARM[] (unsigned 8-bit) and the loop points

Firmware plays the recording from the start (the engine starting), then repeats the loop.
Standard library only.
"""
import argparse, math, os, struct, sys, wave

ap = argparse.ArgumentParser()
ap.add_argument("wav")
ap.add_argument("-o", "--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "include", "user_sounds.h"))
ap.add_argument("--loop-start", type=float, default=3.6, help="earliest loop start, seconds after the trimmed start (default 3.6)")
ap.add_argument("--min-loop", type=float, default=2.0, help="shortest loop, seconds (default 2.0)")
ap.add_argument("--xfade-ms", type=float, default=100.0, help="crossfade length used by the firmware, ms (default 100)")
a = ap.parse_args()

w = wave.open(a.wav)
sr, ch, sw, n = w.getframerate(), w.getnchannels(), w.getsampwidth(), w.getnframes()
raw = w.readframes(n)
if ch != 1:
    sys.exit("mono WAV required")
if sw == 1:
    x = [(b - 128) / 128.0 for b in raw]
elif sw == 2:
    x = [v / 32768.0 for v in struct.unpack("<%dh" % n, raw)]
else:
    sys.exit("only 8/16-bit WAV supported")
if sr != 22050:
    print("WARNING: sample rate is %d Hz, firmware assumes 22050 Hz (pitch/speed will be off)" % sr)

# remove DC
mean = sum(x) / len(x)
x = [v - mean for v in x]

# trim leading silence (keep 50 ms before the first sample above 15 % of full scale)
first = next((i for i, v in enumerate(x) if abs(v) > 0.15), 0)
t0 = max(0, first - int(0.05 * sr))
x = x[t0:]
N = len(x)
X = int(a.xfade_ms / 1000.0 * sr)

ls0 = int(a.loop_start * sr)
if ls0 < X or N < ls0 + int((a.min_loop + 0.5) * sr):
    sys.exit("recording too short for the chosen loop parameters")


def score(ls, le, step=1, wlen=None):
    """Normalised correlation of the samples before le with the samples before ls."""
    wl = wlen or X
    num = ea = eb = 0.0
    for k in range(0, wl, step):
        p, q = x[le - wl + k], x[ls - wl + k]
        num += p * q
        ea += p * p
        eb += q * q
    return num / math.sqrt(ea * eb + 1e-12)


# coarse search (loop start every 0.05 s, loop end every 8 samples, decimated windows),
# then refine at full resolution
best, bls, ble = -2, ls0, ls0 + int(a.min_loop * sr)
for ls in range(ls0, min(ls0 + int(1.0 * sr), N - int((a.min_loop + 0.3) * sr)), int(0.05 * sr)):
    for le in range(ls + int(a.min_loop * sr), N - 3, 8):
        sc = score(ls, le, step=8)
        if sc > best:
            best, bls, ble = sc, ls, le
best, ls, le = -2, bls, ble
for ls_c in range(max(ls0, bls - 8), bls + 9, 2):
    for le_c in range(max(ls_c + int(a.min_loop * sr), ble - 8), min(N - 3, ble + 9)):
        sc = score(ls_c, le_c)
        if sc > best:
            best, ls, le = sc, ls_c, le_c

print("trimmed start: %.3f s, length %.2f s" % (t0 / sr, N / sr))
print("loop %.3f .. %.3f s (%.2f s long), seam correlation %.2f" % (ls / sr, le / sr, (le - ls) / sr, best))

data = [max(0, min(255, int(round(v * 127 + 128)))) for v in x]
with open(a.out, "w") as fh:
    fh.write("// Generated by tools/make_user_sounds.py - do not edit, do NOT commit (license of the source recording unknown).\n")
    fh.write("#pragma once\n#include <stdint.h>\n")
    fh.write("#define START_WARM_RATE %d\n#define START_WARM_LEN %d\n" % (sr, N))
    fh.write("#define LOOP_START %d\n#define LOOP_END %d\n" % (ls, le))
    fh.write("static const uint8_t START_WARM[START_WARM_LEN] = {\n")
    for i in range(0, N, 24):
        fh.write(",".join(str(v) for v in data[i:i + 24]) + ",\n")
    fh.write("};\n")
print("wrote", os.path.abspath(a.out))
