#!/usr/bin/env python3
r"""Spoken numbers 1..99 for the web page (docs/user-sounds.md, "Announcing the set"): the default name of a set is its
number, "One." ... "Ninety nine.", spoken by Piper (en_US-ljspeech, public domain voice) like the names of the default
sets. They are stored compressed (Opus in Ogg, 24 kbit/s, about 0.2 MB for all) as base64 in web/number_names.js, which
the page decodes and converts to the module's WAV format, so the page needs no download for the number.

    python tools/make_number_names.py --piper C:/path/to/piper_tts/piper --model C:/path/to/piper_tts/en_US-ljspeech-medium.onnx

Needs piper.exe (downloaded by the user, see "Making the name" in docs/user-sounds.md) and ffmpeg with libopus on the PATH.
The output is committed (small); regenerate only to change the voice. The sounds are Piper output of a public-domain
voice, ours (MIT, like the rest).
"""
import argparse, base64, json, os, subprocess, sys, tempfile, wave
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_default_sets as D   # piper_name(): speaks, resamples to 22 050 Hz, trims, fades, peak -1 dBFS

OUT = os.path.join(D.ROOT, "web", "number_names.js")
ONES = ["", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve",
        "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen"]
TENS = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"]


def words(n):
    s = ONES[n] if n < 20 else TENS[n // 10] + (" " + ONES[n % 10] if n % 10 else "")
    return s.capitalize() + "."


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--piper", required=True); ap.add_argument("--model", required=True)
    a = ap.parse_args()
    out, total = {}, 0
    with tempfile.TemporaryDirectory() as tmp:
        for n in range(1, 100):
            pcm = D.piper_name(words(n), a.piper, a.model)
            wav = os.path.join(tmp, "n.wav"); ogg = os.path.join(tmp, "n.ogg")
            with wave.open(wav, "wb") as w:
                w.setnchannels(1); w.setsampwidth(2); w.setframerate(D.RATE); w.writeframes(pcm.tobytes())
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", wav, "-c:a", "libopus", "-b:a", "24k",
                            "-application", "voip", ogg], check=True)
            data = open(ogg, "rb").read(); total += len(data)
            out["%02d" % n] = base64.b64encode(data).decode()
            print("%02d %-14s %.2f s  %5d bytes" % (n, words(n), len(pcm) / D.RATE, len(data)))
    with open(OUT, "w", encoding="utf8", newline="\n") as f:
        f.write("// Generated by tools/make_number_names.py: the numbers 1..99 spoken by Piper, Opus in Ogg, base64.\n")
        f.write("window.NUMBER_NAMES = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("total", total, "bytes of audio,", os.path.getsize(OUT), "bytes in", OUT)


if __name__ == "__main__":
    main()
