#!/usr/bin/env python3
"""Convert a WAV loop to a seamless mono 16-bit 22.05 kHz C array.

Usage: python tools/make_sample.py assets/samples/loop_2.wav firmware/include/engine_sample.h
Uses only the standard library. Resamples with linear interpolation and
cross-fades the loop end into its start so the loop point does not click.
"""
import sys, wave, struct

RATE = 22050
XFADE = 0.04  # seconds


def main(src, dst):
    w = wave.open(src)
    assert w.getnchannels() == 1 and w.getsampwidth() == 2, "mono 16-bit WAV expected"
    n = w.getnframes()
    d = struct.unpack("<%dh" % n, w.readframes(n))
    r = w.getframerate()
    m = int(n * RATE / r)
    out = []
    for i in range(m):
        p = i * (n - 1) / (m - 1)
        k = int(p)
        f = p - k
        a = d[k]
        b = d[min(k + 1, n - 1)]
        out.append(a + (b - a) * f)
    # Cross-fade: the first x samples blend from the audio that precedes the
    # cut (the tail) into the real start, so wrapping to the start is continuous.
    x = int(XFADE * RATE)
    body = out[: m - x]
    tail = out[m - x:]
    for i in range(x):
        t = i / x
        body[i] = body[i] * t + tail[i] * (1 - t)
    body = [max(-32768, min(32767, int(round(v)))) for v in body]
    with open(dst, "w") as fh:
        fh.write("// Generated by tools/make_sample.py - do not edit.\n")
        fh.write("// Source: %s (CC0, see assets/samples/LICENSE-SAMPLES.md)\n" % src)
        fh.write("#pragma once\n#include <stdint.h>\n")
        fh.write("#define ENGINE_SAMPLE_RATE %d\n" % RATE)
        fh.write("#define ENGINE_SAMPLE_LEN %d\n" % len(body))
        fh.write("static const int16_t ENGINE_SAMPLE[ENGINE_SAMPLE_LEN] = {\n")
        for i in range(0, len(body), 16):
            fh.write(",".join(str(v) for v in body[i:i + 16]) + ",\n")
        fh.write("};\n")
    print("wrote %s: %d samples (%.3f s)" % (dst, len(body), len(body) / RATE))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
