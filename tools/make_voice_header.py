#!/usr/bin/env python3
"""Turn spoken prompt WAVs into firmware/include/voice_prompts.h (for the `engine_lab` test firmware).

Each WAV (16-bit, any rate, mono or stereo) is resampled to 22.05 kHz, trimmed of leading and trailing silence,
high-passed (the speaker plays nothing below about 250 Hz and only distorts there) and normalised.
The prompts come from Piper text-to-speech with the public-domain-trained en_US-ljspeech voice
(tools/make_voice_prompts.ps1); the generated header is kept in git (licence-clean). Without it engine_lab
announces the sound with beeps instead.

Usage: python tools/make_voice_header.py voice_1.wav voice_2.wav ... [--out firmware/include/voice_prompts.h]
Needs numpy.
"""
import argparse, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from speaker_model import read_wav  # noqa: E402
from engine_lab import Chain, biquad, ROOT  # noqa: E402

RATE = 22050
PEAK = 0.7


def prepare(path):
    x, rate = read_wav(path)
    if rate != RATE:
        t = np.arange(int(len(x) * RATE / rate)) * rate / RATE
        x = np.interp(t, np.arange(len(x)), x)
    thr = 0.02 * np.max(np.abs(x))
    idx = np.nonzero(np.abs(x) > thr)[0]
    a, b = max(0, idx[0] - int(0.02 * RATE)), min(len(x), idx[-1] + int(0.05 * RATE))
    x = x[a:b]
    hp = Chain([biquad("hp", 250, 0.5412), biquad("hp", 250, 1.3066)])
    x = np.array([hp(v) for v in x])
    x *= PEAK / np.max(np.abs(x))
    fade = int(0.01 * RATE)
    x[:fade] *= np.linspace(0, 1, fade); x[-fade:] *= np.linspace(1, 0, fade)
    return np.round(x * 32767).astype(int)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("wavs", nargs="+")
    ap.add_argument("--out", default=os.path.join(ROOT, "firmware", "include", "voice_prompts.h"))
    a = ap.parse_args()
    clips = [prepare(p) for p in a.wavs]
    with open(a.out, "w") as fh:
        fh.write("// Generated by tools/make_voice_header.py - do not edit. Piper en_US-ljspeech voice (LJ Speech dataset, public domain).\n")
        fh.write("#pragma once\n#include <stdint.h>\n#define VOICE_PROMPTS %d\n" % len(clips))
        for i, c in enumerate(clips):
            fh.write("static const int16_t VOICE_%d[%d] = {\n" % (i, len(c)))
            for k in range(0, len(c), 24):
                fh.write(",".join(str(v) for v in c[k:k + 24]) + ",\n")
            fh.write("};\n")
        fh.write("static const int16_t* const VOICE_DATA[VOICE_PROMPTS] = {%s};\n"
                 % ", ".join("VOICE_%d" % i for i in range(len(clips))))
        fh.write("static const uint32_t VOICE_LEN[VOICE_PROMPTS] = {%s};\n" % ", ".join(str(len(c)) for c in clips))
    print("wrote %s: %s" % (a.out, ", ".join("%.2f s" % (len(c) / RATE) for c in clips)))


if __name__ == "__main__":
    main()
