#!/usr/bin/env python3
"""Synthesise a seamless engine loop (firing pulses) and write firmware/include/engine_sample.h.

Why: the CC0 loops in assets/samples are almost pure 40-80 Hz tones (99.99 % of the energy
below 500 Hz). A 40 mm speaker cannot reproduce that, so it sounds like quiet hiss.
This generator builds a loop from short exhaust-like pulses (rich in harmonics between
300 Hz and 4 kHz) that a small speaker can play. Pitch is changed in firmware by the
playback rate. Standard library only.

Usage: python tools/make_engine_synth.py [output.h]
"""
import math, os, random, sys

RATE = 22050
F0 = 90            # firing frequency in the loop at playback rate 1.0 (Hz)
CYCLES = 8         # firing pulses per loop; loop length = CYCLES * period
PERIOD = RATE // F0
L = PERIOD * CYCLES
PEAK = 0.85        # peak of the loop as a fraction of full scale
random.seed(7)     # reproducible

buf = [0.0] * L
for c in range(CYCLES):
    amp = 0.75 + 0.25 * random.random()          # slightly uneven pulses
    start = c * PERIOD + random.randint(-6, 6)   # slight timing jitter
    n = PERIOD * 2                                # pulse tail may spill into the next period
    for t in range(n):
        env = math.exp(-t / 70.0)
        body = math.sin(2 * math.pi * 600 * t / RATE) + 0.7 * math.sin(2 * math.pi * 1100 * t / RATE + 0.6) + 0.45 * math.sin(2 * math.pi * 1900 * t / RATE + 1.0)
        crack = (random.random() * 2 - 1) * math.exp(-t / 10.0) * 0.8
        thump = 0.45 * math.exp(-t / 90.0) * math.sin(2 * math.pi * 130 * t / RATE)
        buf[(start + t) % L] += amp * (env * body + crack + thump)

# remove DC, soft-clip (raises the average level of the sparse pulses), normalise
mean = sum(buf) / L
buf = [v - mean for v in buf]
m0 = max(abs(v) for v in buf)
buf = [math.tanh(2.4 * v / m0) for v in buf]
m = max(abs(v) for v in buf)
data = [int(round(v / m * PEAK * 32767)) for v in buf]

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "include", "engine_sample.h")
with open(out, "w") as fh:
    fh.write("// Generated by tools/make_engine_synth.py - do not edit.\n")
    fh.write("// Synthesised engine firing-pulse loop (original, no third-party audio).\n")
    fh.write("#pragma once\n#include <stdint.h>\n")
    fh.write("#define ENGINE_SAMPLE_RATE %d\n#define ENGINE_SAMPLE_LEN %d\n" % (RATE, L))
    fh.write("static const int16_t ENGINE_SAMPLE[ENGINE_SAMPLE_LEN] = {\n")
    for i in range(0, L, 16):
        fh.write(",".join(str(v) for v in data[i:i + 16]) + ",\n")
    fh.write("};\n")
print("wrote %s: %d samples (%.3f s), firing %d Hz" % (out, L, L / RATE, F0))
