#!/usr/bin/env python3
"""Convert a loop WAV (mono 16 bit) into a firmware header with an int16 array (standard library only).

Usage: python tools/make_engine_diesel.py [input.wav output.h [PREFIX]]
PREFIX names the macros and the array (default ENGINE_SAMPLE: ENGINE_SAMPLE_RATE, ENGINE_SAMPLE_LEN, ENGINE_SAMPLE).
Default: assets/samples/diesel_idle_loop.wav -> firmware/include/engine_diesel.h
Truck:   python tools/make_engine_diesel.py assets/samples/truck_idle_loop.wav firmware/include/engine_truck.h
"""
import os, sys, wave, struct

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 2 else os.path.join(here, "..", "assets", "samples", "diesel_idle_loop.wav")
prefix = sys.argv[3] if len(sys.argv) > 3 else "ENGINE_SAMPLE"
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "firmware", "include", "engine_diesel.h")

with wave.open(src, "rb") as w:
    assert w.getnchannels() == 1 and w.getsampwidth() == 2, "expected mono 16 bit"
    rate, n = w.getframerate(), w.getnframes()
    data = struct.unpack("<%dh" % n, w.readframes(n))

with open(out, "w") as fh:
    fh.write("// Generated by tools/make_engine_diesel.py - do not edit.\n")
    fh.write("// Idle loop of a diesel engine from a CC0 recording (%s), see assets/samples/LICENSE-SAMPLES.md.\n" % os.path.basename(src))
    fh.write("#pragma once\n#include <stdint.h>\n")
    fh.write("#define %s_RATE %d\n#define %s_LEN %d\n" % (prefix, rate, prefix, n))
    fh.write("static const int16_t %s[%s_LEN] = {\n" % (prefix, prefix))
    for i in range(0, n, 16):
        fh.write(",".join(str(v) for v in data[i:i + 16]) + ",\n")
    fh.write("};\n")
print("wrote %s: %d samples (%.3f s at %d Hz)" % (out, n, n / rate, rate))
