#!/usr/bin/env python3
"""Convert assets/samples/diesel_idle_loop.wav into firmware/include/engine_diesel.h (int16 array, standard library only).

Usage: python tools/make_engine_diesel.py [output.h]
"""
import os, sys, wave, struct

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "assets", "samples", "diesel_idle_loop.wav")
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "firmware", "include", "engine_diesel.h")

with wave.open(src, "rb") as w:
    assert w.getnchannels() == 1 and w.getsampwidth() == 2, "expected mono 16 bit"
    rate, n = w.getframerate(), w.getnframes()
    data = struct.unpack("<%dh" % n, w.readframes(n))

with open(out, "w") as fh:
    fh.write("// Generated by tools/make_engine_diesel.py - do not edit.\n")
    fh.write("// Idle loop of a diesel engine, from chlund's recording (CC0), see assets/samples/LICENSE-SAMPLES.md.\n")
    fh.write("#pragma once\n#include <stdint.h>\n")
    fh.write("#define ENGINE_SAMPLE_RATE %d\n#define ENGINE_SAMPLE_LEN %d\n" % (rate, n))
    fh.write("static const int16_t ENGINE_SAMPLE[ENGINE_SAMPLE_LEN] = {\n")
    for i in range(0, n, 16):
        fh.write(",".join(str(v) for v in data[i:i + 16]) + ",\n")
    fh.write("};\n")
print("wrote %s: %d samples (%.3f s at %d Hz)" % (out, n, n / rate, rate))
