#!/usr/bin/env python3
"""Generate the combustion "grains" used by the pulse-based engine synth.

Idea: instead of pitch-shifting one recorded loop (which also shifts the timbre, so the engine
sounds like a siren / chipmunk), the firmware triggers a short, fixed-timbre exhaust pulse
(a "grain") at the engine firing rate. RPM only changes how often grains are triggered, so the
body of the sound stays the same, as in a real engine.

Two grain sets, 4 slightly different variants each (avoids a machine-gun repetition):
  BASE   - dull exhaust "thump" with mid-frequency body (audible on a small speaker)
  BRIGHT - sharper crack, mixed in when the throttle is pushed (engine under load)

Output: firmware/include/engine_grains.h. Standard library only, deterministic.
Usage: python tools/make_engine_grains.py [output.h]
"""
import math, os, random, sys

RATE = 22050
LEN = 384            # 17.4 ms per grain
VARIANTS = 4
random.seed(11)


def lowpass_noise(n, a):
    y, out = 0.0, []
    for _ in range(n):
        y += a * ((random.random() * 2 - 1) - y)
        out.append(y)
    return out


def make_grain(bright):
    # slight random detune per variant
    d = lambda f: f * (1 + (random.random() - 0.5) * 0.08)
    ph = lambda: random.random() * 2 * math.pi
    base = [
        # (freq Hz, amplitude, decay time s)
        (d(150), 0.35, 0.0060),
        (d(330), 0.60, 0.0050),
        (d(620), 0.85, 0.0040),
        (d(980), 0.75, 0.0032),
        (d(1500), 0.50, 0.0026),
    ]
    hi = [(d(2300), 0.55, 0.0020), (d(3300), 0.38, 0.0014)]
    comps = hi if bright else base
    comps = [(f, a, tau, ph()) for f, a, tau in comps]
    noise = lowpass_noise(LEN, 0.55 if not bright else 0.95)
    g = []
    for t in range(LEN):
        ts = t / RATE
        v = 0.0
        for f, a, tau, p in comps:
            v += a * math.sin(2 * math.pi * f * ts + p) * math.exp(-ts / tau)
        v += (0.45 if not bright else 0.85) * noise[t] * math.exp(-ts / (0.0016 if not bright else 0.0008))
        attack = min(1.0, (t + 1) / 6.0)   # very short ramp, removes the click
        g.append(v * attack)
    # fade the tail to zero
    for t in range(LEN - 48, LEN):
        g[t] *= (LEN - t) / 48.0
    return g


def normalise(g, peak):
    m = max(abs(v) for v in g)
    return [int(round(v / m * peak * 32767)) for v in g]


base = [normalise(make_grain(False), 0.90) for _ in range(VARIANTS)]
bright = [normalise(make_grain(True), 0.80) for _ in range(VARIANTS)]

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "include", "engine_grains.h")
with open(out, "w") as fh:
    fh.write("// Generated by tools/make_engine_grains.py - do not edit.\n")
    fh.write("// Synthesised combustion grains (original, no third-party audio).\n")
    fh.write("#pragma once\n#include <stdint.h>\n")
    fh.write("#define GRAIN_RATE %d\n#define GRAIN_LEN %d\n#define GRAIN_VARIANTS %d\n" % (RATE, LEN, VARIANTS))
    for name, arr in (("GRAIN_BASE", base), ("GRAIN_BRIGHT", bright)):
        fh.write("static const int16_t %s[GRAIN_VARIANTS][GRAIN_LEN] = {\n" % name)
        for g in arr:
            fh.write("{\n")
            for i in range(0, LEN, 16):
                fh.write(",".join(str(v) for v in g[i:i + 16]) + ",\n")
            fh.write("},\n")
        fh.write("};\n")
print("wrote %s: %d variants x %d samples x 2 sets" % (out, VARIANTS, LEN))
