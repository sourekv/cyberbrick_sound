#!/usr/bin/env python3
"""Cut the gear-shift sound from the CC0 recording and turn it into a firmware header.

Usage: python tools/make_shift_sound.py ORIGINAL.wav
  ORIGINAL: "G13.1-04-Old Car Gearshift Grind.wav" by craigsmith, https://freesound.org/s/438031/ (CC0),
  72 s, 48 kHz 24 bit mono (not stored in the repo).
Writes assets/samples/shift_grind.wav (22.05 kHz mono 16 bit) and firmware/include/shift_sound.h (SHIFT_SOUND).

The cut is event 21 of the 24 loud events in the recording (picked by ear on 2026-11-08): 0.35 s from 62.79 s,
high-passed at 200 Hz (the recording has a strong hum around 100 Hz that the small speaker cannot play anyway),
5 ms fade-in, 60 ms fade-out, normalised to full scale. Needs numpy.
"""
import math, os, sys, wave
import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RATE = 22050
START, LENGTH = 62.79, 0.35
HP_HZ = 200.0


def read_wav(path):
    w = wave.open(path)
    ch, width, fs, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    raw = w.readframes(n)
    w.close()
    if width == 3:
        b = np.frombuffer(raw, np.uint8).reshape(-1, 3).astype(np.int32)
        d = (b[:, 0] | (b[:, 1] << 8) | (b[:, 2] << 16))
        d = np.where(d >= 1 << 23, d - (1 << 24), d) / float(1 << 23)
    elif width == 2:
        d = np.frombuffer(raw, "<i2") / 32768.0
    else:
        raise SystemExit("16 or 24 bit WAV expected")
    return d.reshape(-1, ch).mean(axis=1), fs


def biquad_hp(x, f0, q, fs):
    w = 2 * math.pi * f0 / fs
    al, c = math.sin(w) / (2 * q), math.cos(w)
    b = np.array([(1 + c) / 2, -(1 + c), (1 + c) / 2]) / (1 + al)
    a1, a2 = -2 * c / (1 + al), (1 - al) / (1 + al)
    y = np.zeros_like(x)
    x1 = x2 = y1 = y2 = 0.0
    for i, v in enumerate(x):
        o = b[0] * v + b[1] * x1 + b[2] * x2 - a1 * y1 - a2 * y2
        x2, x1, y2, y1 = x1, v, y1, o
        y[i] = o
    return y


def resample(x, fs, to):
    # low-pass (windowed sinc at 0.45 * new rate), then linear interpolation
    fc = 0.45 * to / fs
    k = np.arange(-64, 65)
    h = 2 * fc * np.sinc(2 * fc * k) * np.hamming(len(k))
    x = np.convolve(x, h / h.sum(), mode="same")
    t = np.arange(int(len(x) * to / fs)) * fs / to
    return np.interp(t, np.arange(len(x)), x)


def main(src):
    x, fs = read_wav(src)
    a = int((START - 0.5) * fs)                     # filter from a bit earlier, so the filter has settled
    seg = x[a:int((START + LENGTH) * fs)]
    seg = biquad_hp(biquad_hp(seg, HP_HZ, 0.5412, fs), HP_HZ, 1.3066, fs)   # 4th-order Butterworth high-pass
    seg = seg[int(0.5 * fs):]
    y = resample(seg, fs, RATE)
    fi, fo = int(0.005 * RATE), int(0.06 * RATE)
    y[:fi] *= np.linspace(0, 1, fi)
    y[-fo:] *= np.linspace(1, 0, fo)
    y = y / np.abs(y).max() * 0.98
    pcm = np.round(y * 32767).astype("<i2")

    wav_path = os.path.join(ROOT, "assets", "samples", "shift_grind.wav")
    w = wave.open(wav_path, "wb")
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE)
    w.writeframes(pcm.tobytes())
    w.close()

    h_path = os.path.join(ROOT, "firmware", "include", "shift_sound.h")
    with open(h_path, "w", newline="\n") as f:
        f.write("// Gear-shift sound, generated by tools/make_shift_sound.py from assets/samples/shift_grind.wav\n")
        f.write("// Source: \"G13.1-04-Old Car Gearshift Grind.wav\" by craigsmith, https://freesound.org/s/438031/ (CC0)\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write("#define SHIFT_SOUND_RATE %d\n#define SHIFT_SOUND_LEN %d\n" % (RATE, len(pcm)))
        f.write("static const int16_t SHIFT_SOUND[SHIFT_SOUND_LEN] = {\n")
        for i in range(0, len(pcm), 16):
            f.write("  " + ", ".join(str(int(v)) for v in pcm[i:i + 16]) + ",\n")
        f.write("};\n")
    print("%s: %d samples (%.2f s)" % (wav_path, len(pcm), len(pcm) / RATE))
    print(h_path)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
