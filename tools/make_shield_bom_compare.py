"""Comparison BOM of the shield: the ideal parts (fab/shield_bom.csv, the full BOM of the design) against the parts that
were ordered at JLCPCB for rev A on 2026-11-13 (fab/jlcpcb_basic/shield_bom_jlcpcb.csv, the basic-parts variant).

    python3 tools/make_shield_bom_compare.py

Output: hardware/shield/fab/shield_bom_compare.csv and a markdown table in docs/shield-bom-compare.md.
Regenerate after changing either BOM; the notes on the differences are in NOTES below.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FAB = ROOT / "hardware" / "shield" / "fab"
IDEAL = FAB / "shield_bom.csv"
ORDERED = FAB / "jlcpcb_basic" / "shield_bom_jlcpcb.csv"
OUT_CSV = FAB / "shield_bom_compare.csv"
OUT_MD = ROOT / "docs" / "shield-bom-compare.md"

# what differs and what it means (checked 2026-11-14); keys are designators
NOTES = {
    "C3": "Samsung CL10B104KB8NNNC -> YAGEO CC0603KRX7R9BB104: the same 100 nF 50 V X7R 0603, no effect",
    "FB1": "Murata BLM18KG601SN1D (600 R, 1.3 A) -> BLM18PG121SN1D (120 R, 2 A): weaker filtering of the amplifier's "
           "switching noise on the speaker wires, lower resistance; the beads are optional in the design (can be 0 R)",
    "LED1": "Kento KT-0603G green -> KT-0603R red: no green 0603 LED among JLCPCB's basic parts; the red one has a lower "
            "drop, so a little more than the 3 mA through the 1 k resistor (to be seen at the first power-up)",
}
NOTES.update({"C6": NOTES["C3"], "C7": NOTES["C3"], "FB2": NOTES["FB1"]})


def expand(refs):
    return [r.strip() for r in refs.split(",")]


def main():
    ordered = {}
    for row in csv.DictReader(open(ORDERED, encoding="utf8")):
        for ref in expand(row["Designator"]):
            ordered[ref] = (row["Comment"], row["LCSC"])
    rows = []
    for row in csv.DictReader(open(IDEAL, encoding="utf8")):
        for ref in expand(row["Designators"].strip('"')):
            iv, il = row["Value"], row["LCSC"]
            if ref in ordered:
                ov, ol = ordered[ref]
                status = "same" if (ol == il) else "different"
            elif il == "hand-soldered":
                ov, ol, status = iv, il, "hand-soldered"
            else:
                ov, ol, status = "", "", "no part (solder jumper)"
            rows.append([ref, row["Footprint"], iv, il, ov, ol, status, NOTES.get(ref, "")])
    key = lambda r: (r[0].rstrip("0123456789"), int("".join(c for c in r[0] if c.isdigit())))
    rows.sort(key=key)
    head = ["Ref", "Footprint", "Ideal value", "Ideal LCSC", "Ordered value", "Ordered LCSC", "Status", "Note"]
    with open(OUT_CSV, "w", newline="", encoding="utf8") as f:
        w = csv.writer(f); w.writerow(head); w.writerows(rows)
    diff = [r for r in rows if r[6] == "different"]
    md = ["| Ref | Ideal (full BOM) | Ordered (basic-parts variant) | Status |", "|---|---|---|---|"]
    for r in rows:
        ideal = f"{r[2]} ({r[3]})" if r[3] else r[2]
        ordd = f"{r[4]} ({r[5]})" if r[4] else "-"
        md.append(f"| {r[0]} | {ideal} | {ordd} | " + (f"**{r[6]}**" if r[6] == "different" else r[6]) + " |")
    OUT_MD.write_text(
        "# Shield rev A: ideal parts against the ordered ones\n\n"
        "Generated by `tools/make_shield_bom_compare.py` from `hardware/shield/fab/shield_bom.csv` (the ideal, full BOM of "
        "the design) and `fab/jlcpcb_basic/shield_bom_jlcpcb.csv` (what was ordered at JLCPCB on 2026-11-13). "
        "The same table as CSV: `hardware/shield/fab/shield_bom_compare.csv`.\n\n"
        f"{len(diff)} of {len(rows)} references differ, in three groups, all chosen to get JLCPCB's basic parts (about 9 USD "
        "less in loading fees):\n\n"
        + "\n".join(f"- **{k}**: {v}" for k, v in {"C3, C6, C7": NOTES["C3"], "FB1, FB2": NOTES["FB1"],
                                                  "LED1": NOTES["LED1"]}.items())
        + "\n\nJ1, J3 and J4 are not in JLCPCB's assembly and are soldered by hand; JP1 and JP2 are solder jumpers on the "
        "board, not parts.\n\n" + "\n".join(md) + "\n", encoding="utf8", newline="")
    print(len(rows), "references,", len(diff), "differ")


if __name__ == "__main__":
    main()
